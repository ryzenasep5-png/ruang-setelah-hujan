export const quotes: Quote[] = (Object.entries(quoteTextByCategory) as [QuoteCategory, string[]][]).flatMap(
  ([category, texts]) =>
    texts.map((text, index) => ({
      id: `${category}-${String(index + 1).padStart(2, '0')}`,
      text,
      category,
    })),
)

export const QUOTES = quotes

export function getQuotesByCategory(category: QuoteCategory): Quote[] {
  return quotes.filter((quote) => quote.category === category)
}

export function getRandomQuote(category?: QuoteCategory): Quote {
  const pool = category ? getQuotesByCategory(category) : quotes
  return pool[Math.floor(Math.random() * pool.length)] ?? quotes[0]
}
